// Command paritytests writes notes/parity-tests.md: a checklist of patent's
// tests, each ticked off with the Go test that ports it.
//
// A Rust test is matched to a Go test automatically when their names agree
// once case and underscores are ignored (crates_io_maps_results_into_matches
// and TestCratesIOMapsResultsIntoMatches). Tests that were renamed, split or
// that don't apply are listed in manual below.
//
// Run it from the repository root:
//
//	go run ./scripts/paritytests -patent ~/code/r14dd/patent
package main

import (
	"bufio"
	"flag"
	"fmt"
	"io/fs"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

// manual maps "file::rust_test_name" to the Go tests that port it, or to a
// single "n/a: reason" entry.
var manual = map[string][]string{
	"src/sources/mod.rs::from_str_parses_known_sources": {"model.TestParseSource", "model.TestParseSourceErrorListsValidNames"},
	"tests/sources.rs::a_malformed_date_never_fails_its_source": {
		"sources.TestCratesIOMalformedDateNeverFailsTheSource",
		"sources.TestGitHubMalformedDateNeverFailsTheSource",
		"sources.TestNpmMalformedDateNeverFailsTheSource",
		"sources.TestHexMalformedDateNeverFailsTheSource",
		"sources.TestMavenMalformedDateNeverFailsTheSource",
		"sources.TestAURMalformedDateNeverFailsTheSource",
		"sources.TestArtifactHubMalformedDateNeverFailsTheSource",
		"sources.TestJetBrainsWrongTypeCdateDegradesToNoneNotError",
	},
	"tests/sources.rs::test_homebrew_happy_path":    {"sources.TestHomebrewHappyPath"},
	"tests/sources.rs::test_homebrew_empty_results": {"sources.TestHomebrewEmptyResults"},
	"tests/sources.rs::test_homebrew_server_error":  {"sources.TestHomebrewServerError"},
}

// notApplicable gives the reason why the tests of a file that silt doesn't
// port are n/a. Those of its tests that a Go test of the same name covers
// are still ticked off.
var notApplicable = map[string]string{
	"src/tui.rs":               tuiReason,
	"src/bin/patent/tui.rs":    tuiReason,
	"tests/tui.rs":             tuiReason,
	"src/bin/patent/config.rs": llmReason,
	"tests/ollama.rs":          llmReason,
	"tests/openai.rs":          llmReason,
	"tests/verdict.rs":         llmReason,
}

const tuiReason = "silt's TUI is its own design, inspired by patent's (D7), so these tests " +
	"of patent's state machine and renderer don't apply. internal/tui tests what " +
	"they protect: the integrity rules, the keys, filtering, sorting, the details " +
	"and the search."

const llmReason = "silt has no LLM verdict (D8): the verdict always comes from the " +
	"similarity data, so patent's LLM backends, its prompt, the guards on the " +
	"model's answer, and the config file that held the model settings are gone. " +
	"The tests of the verdict from the data are ported."

var (
	rustAttr = regexp.MustCompile(`^\s*#\[(tokio::)?test(\(.*\))?\]`)
	rustFn   = regexp.MustCompile(`^\s*(?:pub\s+)?(?:async\s+)?fn\s+(\w+)`)
	// tests/live.rs stamps out one test per adapter with a macro,
	// live!(name, ...), whose first argument is on the next line.
	liveMacro = regexp.MustCompile(`^live!\($`)
	macroName = regexp.MustCompile(`^\s*(\w+),`)
	goTest    = regexp.MustCompile(`^func (Test\w+)\(t \*testing\.T\)`)
)

type rustTest struct{ file, name string }

func main() {
	patent := flag.String("patent", filepath.Join(os.Getenv("HOME"), "code/r14dd/patent"), "patent checkout")
	out := flag.String("o", "notes/parity-tests.md", "output file")
	flag.Parse()

	tests, err := rustTests(*patent)
	if err != nil {
		log.Fatal(err)
	}
	ported, err := goTests(".")
	if err != nil {
		log.Fatal(err)
	}

	var (
		b           strings.Builder
		sections    []string
		done, notAp int
	)
	byFile := make(map[string][]rustTest)
	var files []string
	for _, t := range tests {
		if _, ok := byFile[t.file]; !ok {
			files = append(files, t.file)
		}
		byFile[t.file] = append(byFile[t.file], t)
	}
	for _, f := range files {
		var lines []string
		n := 0
		reason, na := notApplicable[f]
		for _, t := range byFile[f] {
			targets := manual[t.file+"::"+t.name]
			if targets == nil {
				if g, ok := ported[normalize(t.name)]; ok {
					targets = []string{g}
				}
			}
			box := " "
			switch {
			case targets != nil:
				box = "x"
				n++
			case na:
				box = "-"
				notAp++
			}
			line := fmt.Sprintf("- [%s] `%s`", box, t.name)
			if targets != nil {
				line += " → " + strings.Join(targets, ", ")
			}
			lines = append(lines, line)
		}
		done += n
		heading := fmt.Sprintf("## %s (%d/%d)\n\n", f, n, len(byFile[f]))
		if na {
			heading = fmt.Sprintf("## %s (%d/%d, the rest n/a)\n\n%s\n\n", f, n, len(byFile[f]), wrapText(reason, 80))
		}
		sections = append(sections, heading+strings.Join(lines, "\n")+"\n")
	}
	fmt.Fprintf(&b, "# Parity tests\n\n")
	fmt.Fprintf(&b, "patent's tests are the spec for the port (see [todo.md](todo.md)). Each Rust test\n")
	fmt.Fprintf(&b, "below is ticked off with the Go test that ports it, or marked n/a with a reason.\n\n")
	fmt.Fprintf(&b, "Generated by `go run ./scripts/paritytests` from patent 0.14.1 @ `8d741bd`; don't\n")
	fmt.Fprintf(&b, "edit it by hand. Name a Go test after its Rust original and it is matched\n")
	fmt.Fprintf(&b, "automatically; record renamed, split or inapplicable tests in the script.\n\n")
	fmt.Fprintf(&b, "**Ported: %d of %d; n/a: %d ([-]).**\n\n", done, len(tests), notAp)
	b.WriteString(strings.Join(sections, "\n"))
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%s: %d of %d tests ported, %d n/a\n", *out, done, len(tests), notAp)
}

// wrapText wraps s at spaces into lines of at most width bytes.
func wrapText(s string, width int) string {
	var lines []string
	line := ""
	for _, w := range strings.Fields(s) {
		if line != "" && len(line)+1+len(w) > width {
			lines = append(lines, line)
			line = ""
		}
		if line != "" {
			line += " "
		}
		line += w
	}
	return strings.Join(append(lines, line), "\n")
}

// rustTests lists every #[test] and #[tokio::test] in patent's src and tests
// directories, in file order.
func rustTests(root string) ([]rustTest, error) {
	var tests []rustTest
	for _, dir := range []string{"src", "tests"} {
		err := filepath.WalkDir(filepath.Join(root, dir), func(path string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() || !strings.HasSuffix(path, ".rs") {
				return err
			}
			rel, _ := filepath.Rel(root, path)
			found, err := scanRust(path)
			for _, name := range found {
				tests = append(tests, rustTest{file: filepath.ToSlash(rel), name: name})
			}
			return err
		})
		if err != nil {
			return nil, err
		}
	}
	slices.SortStableFunc(tests, func(a, b rustTest) int { return strings.Compare(a.file, b.file) })
	return tests, nil
}

func scanRust(path string) ([]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var names []string
	pending, invocation := false, false
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		switch {
		case liveMacro.MatchString(line):
			invocation = true
		case invocation:
			if m := macroName.FindStringSubmatch(line); m != nil {
				names = append(names, m[1])
			}
			invocation = false
		case rustAttr.MatchString(line):
			pending = true
		case pending:
			// The macro's own template, fn $name(), is not a test.
			if m := rustFn.FindStringSubmatch(line); m != nil {
				names = append(names, m[1])
				pending = false
			} else if strings.Contains(line, "fn $") {
				pending = false
			}
		}
	}
	return names, sc.Err()
}

// goTests maps the normalized name of every Go test in the module to its
// qualified name, e.g. "sources.TestDedupKeepsDistinctURLs".
func goTests(root string) (map[string]string, error) {
	tests := make(map[string]string)
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, "_test.go") {
			return err
		}
		pkg := filepath.Base(filepath.Dir(path))
		if dir := filepath.Dir(path); dir == "." {
			pkg = "silt"
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		for _, line := range strings.Split(string(b), "\n") {
			if m := goTest.FindStringSubmatch(line); m != nil {
				key := normalize(strings.TrimPrefix(m[1], "Test"))
				if _, dup := tests[key]; !dup {
					tests[key] = pkg + "." + m[1]
				}
			}
		}
		return nil
	})
	return tests, err
}

func normalize(name string) string {
	return strings.ToLower(strings.ReplaceAll(name, "_", ""))
}
